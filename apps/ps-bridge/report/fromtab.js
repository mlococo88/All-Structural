/* apps/ps-bridge/report/fromtab.js — an output tab's cards as report items (window.PSBReportTab). Classic script, no DOM.
   Created 2026-11-13 (PR 2e, docs/ps-bridge-plan.md §5: the Report). The Report shows each result tab's own cards: the HTML the tab's
   output(ctx) makes (ui/*.js, the same function and the same engine result R as on screen) is read here, without the DOM, and turned into
   the items of shared/report.js (kv, table, note, steps). So every number in the Report is the number the tab shows, with the same R path:
     <span data-ev="path" data-d="d" data-div="k">text</span>   the value's text, recorded in X.vals as { sec, path, d, div, text }
                                                                (tests/psbridge-compare.mjs compares each with the old app's value)
     <a class="wk" href="#st-ID" data-gotab="T">                "(see §x.y)": a link to the step that works the value (key ID: the step
                                                                ids of the tabs are unique across the app), §x.y in print (CLAUDE.md §6)
     <a data-gotab="T">text</a>                                 an in-app link to that tab, and "(§n)" to its section of the Report
     <a data-goin="T">text</a>                                  an in-app link to that input tab (plain text in print)
     <sub>, <sup>                                               $_{…}$, $^{…}$ (notation of shared/report.js)
   Skipped: the graphics slots (<div id="gfx_…">, drawn after the HTML on screen), the controls (.fRow: a station chooser, buttons), the
   tab's own worked-steps list (the Report puts the tab's steps there itself: report/builders.js). Display only: nothing is calculated.

   parse(html) -> tree; cards(html, o) -> { subs: [{ title, items, steps? }], top: [notes] }; inline(html) -> report text (sub / sup as $…$, tab links as in-app links)
     o.figs (optional, the Report's graphics, 2026-11-13): { <slot id>: [figure items] }: a graphics slot (#gfx_…) of the tab gives its
     figures at its place (a slot outside the cards: in top), instead of nothing
     o = { tab: key of the tab, X: { vals: [] }, sec: the section key recorded with each value, inReport(tab) -> bool (that tab has a
     section in this report) }. A card titled "Worked steps…" comes back as { title, items (its notes), steps: true } for the builder. */
(function () {
  'use strict';
  const VOID = new Set(['br', 'input', 'img', 'hr', 'meta', 'link', 'col', 'wbr', 'source']);
  const ENT = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', '#39': "'" };
  const dec = s => String(s).replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) => e[0] === '#' ? String.fromCodePoint(e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : +e.slice(1)) : (ENT[e] != null ? ENT[e] : m));

  /* ---------- a small parser for the app's own HTML (well formed: generated by ui/*.js) ---------- */
  function parse(html) {
    const root = { tag: '#root', a: {}, kids: [] }, st = [root], re = /<!--[\s\S]*?-->|<(\/?)([a-zA-Z][\w-]*)((?:\s+[^\s=>/]+(?:\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+))?)*)\s*(\/?)>|([^<]+)|(<)/g;
    let m;
    while ((m = re.exec(String(html)))) {
      const top = st[st.length - 1];
      if (m[5] != null || m[6] != null) { top.kids.push({ text: m[5] != null ? m[5] : '<' }); continue; }
      if (!m[2]) continue;   // a comment
      const tag = m[2].toLowerCase();
      if (m[1]) { const i = st.map(n => n.tag).lastIndexOf(tag); if (i > 0) st.length = i; continue; }   // a close tag (an unmatched one is ignored)
      const a = {}; String(m[3] || '').replace(/([^\s=]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g, (x, k, v1, v2, v3) => { a[k.toLowerCase()] = dec(v1 != null ? v1 : v2 != null ? v2 : v3 != null ? v3 : ''); return x; });
      const n = { tag, a, kids: [] }; top.kids.push(n);
      if (!VOID.has(tag) && !m[4]) st.push(n);
    }
    return root;
  }
  const cls = n => ' ' + ((n.a && n.a.class) || '') + ' ';
  const has = (n, c) => !!n.tag && cls(n).includes(' ' + c + ' ');
  const plainText = n => n.text != null ? dec(n.text) : (n.kids || []).map(plainText).join('');

  /* TeX for a sub- or superscript: plain letters and digits as they are, anything else in \text{} (shared/report.js renders $…$ with KaTeX) */
  const GREEK = { 'α': '\\alpha', 'β': '\\beta', 'γ': '\\gamma', 'δ': '\\delta', 'Δ': '\\Delta', 'ε': '\\varepsilon', 'θ': '\\theta', 'λ': '\\lambda', 'μ': '\\mu', 'φ': '\\phi', 'ψ': '\\psi', 'σ': '\\sigma', 'ℓ': '\\ell' };
  const texOf = s => { s = s.replace(/\s+/g, ' ').trim().replace(/−/g, '-').replace(/′/g, "'");
    const g = s.replace(/[αβγδΔεθλμφψσℓ]/g, c => GREEK[c] + ' ').trim(); if (/^(?:[A-Za-z0-9.,+=\-']|\\[a-zA-Z]+ ?)*$/.test(g)) return g;
    return '\\text{' + s.replace(/[\\{}$&#^_%~]/g, c => (c === '\\' ? '\\textbackslash{}' : c === '~' ? '\\textasciitilde{}' : c === '^' ? '\\textasciicircum{}' : '\\' + c)) + '}'; };

  /* ---------- inline text ---------- */
  function txt(n, o) {
    if (n.text != null) return dec(n.text).replace(/\$/g, 'S');
    const t = n.tag, a = n.a || {};
    if (t === 'select' || t === 'button' || t === 'input' || t === 'svg' || t === 'script' || t === 'style' || t === 'option' || t === 'canvas') return '';
    if (t === 'br') return ' ';
    const inner = () => (n.kids || []).map(k => txt(k, o)).join('');
    if (a['data-ev'] != null) { const text = plainText(n).trim(); o.X.vals.push({ sec: o.sec, path: a['data-ev'], d: +a['data-d'], div: a['data-div'] ? +a['data-div'] : 0, text }); return text; }
    if (t === 'sub' || t === 'sup') { const s = plainText(n); return s.trim() ? `$${t === 'sub' ? '_' : '^'}{${texOf(s)}}$` : ''; }
    if (t === 'a') {
      const href = a.href || '', id = /^#st-/.test(href) ? href.slice(4) : null, tab = a['data-gotab'] || null;
      if (has(n, 'wk') || id) { const lab = has(n, 'wk') ? '' : inner(); return `${lab} (see [[${id}]])`; }
      if (tab) { const lab = inner(); return `[[tab:${tab}|${lab.replace(/[[\]|]/g, '')}]]${o.inReport && o.inReport(tab) ? ` ([[rs.${tab}]])` : ''}`; }
      if (a['data-goin']) return `[[tab:in:${a['data-goin']}|${inner().replace(/[[\]|]/g, '')}]]`;
      return inner();
    }
    return inner();
  }
  /* tidy: one space, no space before punctuation, a lone "(see §…)" without its brackets */
  const tidy = s => { s = String(s).replace(/\s+/g, ' ').replace(/\s+([,.;:)])/g, '$1').replace(/\(\s+/g, '(').trim(); const m = /^\(see (\[\[[^\]]+\]\])\)$/.exec(s); return m ? 'see ' + m[1] : s; };
  const line = (n, o) => tidy(txt(n, o));

  /* ---------- blocks ---------- */
  const isNum = s => /^[−\-+]?\(?[\d,]*\.?\d+/.test(s) && !/[A-Za-z]{3,}/.test(s.replace(/\$[^$]*\$/g, '').replace(/\(see \[\[[^\]]*\]\]\)|see \[\[[^\]]*\]\]/g, ''));
  function table(tb, o) {
    const sect = tag => (tb.kids || []).filter(k => k.tag === tag);
    const rowsOf = sec => [].concat(...sec.map(s => (s.kids || []).filter(k => k.tag === 'tr')));
    let headRows = rowsOf(sect('thead')), bodyRows = rowsOf(sect('tbody')).concat((tb.kids || []).filter(k => k.tag === 'tr'));
    if (!headRows.length && bodyRows.length && (bodyRows[0].kids || []).every(c => c.tag !== 'td')) headRows = [bodyRows.shift()];
    // the header rows as one row: each column's texts (rowspan / colspan expanded), top to bottom
    const grid = [];
    headRows.forEach((tr, r) => { grid[r] = grid[r] || []; let c = 0;
      (tr.kids || []).filter(k => k.tag === 'th' || k.tag === 'td').forEach(th => { while (grid[r][c] != null) c++; const t = line(th, o), cs = +(th.a.colspan || 1), rs = +(th.a.rowspan || 1);
        for (let i = 0; i < rs; i++) for (let j = 0; j < cs; j++) { grid[r + i] = grid[r + i] || []; grid[r + i][c + j] = i === 0 ? t : '\u0000'; } c += cs; }); });
    const nc = Math.max(0, ...grid.map(r => r.length));
    const head = [...Array(nc).keys()].map(c => { const ts = []; grid.forEach(r => { const t = r[c]; if (t && t !== '\u0000' && ts[ts.length - 1] !== t) ts.push(t); }); return ts.join(' '); });
    const rows = bodyRows.map(tr => {
      const cells = (tr.kids || []).filter(k => k.tag === 'td' || k.tag === 'th').map(td => { const t = line(td, o), c = { t };
        if (isNum(t)) c.n = true; if (has(td, 'ok')) c.cls = 'ok'; else if (has(td, 'ngt')) c.cls = 'ng'; if (+(td.a.colspan || 1) > 1) c.span = +td.a.colspan; return c; });
      return has(tr, 'ng') ? { cells, cls: 'gov' } : cells;
    });
    return { type: 'table', head, rows, wide: nc > 5 };
  }
  function blocks(n, o, out) {
    (n.kids || []).forEach(k => {
      if (k.text != null) { const t = tidy(dec(k.text)); if (t) out.push({ type: 'note', text: t }); return; }
      const t = k.tag, id = (k.a && k.a.id) || '';
      if (/^gfx_/.test(id)) { if (o.figs && o.figs[id]) out.push(...o.figs[id].map(f => ({ ...f }))); return; }   // a graphics slot: the tab's own figures when given (o.figs), else nothing
      if (has(k, 'fRow') || t === 'select' || t === 'button' || t === 'input' || t === 'svg' || t === 'script' || t === 'style' || t === 'label') return;
      if (has(k, 'kv')) { out.push({ type: 'kv', rows: (k.kids || []).filter(r => r.tag === 'div').map(r => { const sp = (r.kids || []).filter(s => s.tag === 'span'); return [line(sp[0] || { kids: [] }, o), sp.slice(1).map(s => line(s, o)).join(' ')]; }) }); return; }
      if (t === 'table') { out.push(table(k, o)); return; }
      if (has(k, 'alert')) { const ls = (k.kids || []).filter(q => q.tag === 'ul' || q.tag === 'ol'), lead = line({ kids: (k.kids || []).filter(q => q.tag !== 'ul' && q.tag !== 'ol') }, o);
        const items = [].concat(...ls.map(l => (l.kids || []).filter(q => q.tag === 'li').map(q => line(q, o))));
        const text = tidy([lead, items.join('; ')].filter(Boolean).join(items.length && lead ? ': ' : ''));
        if (text) out.push({ type: 'note', text, warn: !has(k, 'ok') }); return; }
      if (t === 'p' || /^h\d$/.test(t)) { const s = line(k, o); if (s) out.push({ type: 'note', text: s }); return; }
      if (t === 'ul' || t === 'ol') { (k.kids || []).filter(q => q.tag === 'li').forEach(q => { const s = line(q, o); if (s) out.push({ type: 'note', text: '• ' + s }); }); return; }
      if (t === 'b' || t === 'span' || t === 'i' || t === 'a' || t === 'sub' || t === 'sup') { const s = line(k, o); if (s) out.push({ type: 'note', text: s }); return; }
      blocks(k, o, out);   // a wrapper (div.tscroll, …)
    });
    return out;
  }
  function cards(html, o) {
    const T = parse(html), subs = [], top = [];
    const walk = n => (n.kids || []).forEach(k => {
      if (k.tag === 'section' && has(k, 'sec')) {
        const hd = (k.kids || []).find(q => has(q, 'secHead')), body = (k.kids || []).find(q => has(q, 'secBody')) || { kids: [] };
        const title = hd ? line(hd, o).replace(/\s*\(see \[\[[^\]]*\]\]\)/g, '') : '';
        if (/^Worked steps/.test(plainText(hd || { kids: [] }).trim())) { const notes = []; (body.kids || []).forEach(q => { if (q.tag === 'p') { const s = line(q, o); if (s) notes.push({ type: 'note', text: s }); } }); subs.push({ title, items: notes, steps: true }); return; }
        subs.push({ title, items: blocks(body, o, []) }); return;
      }
      if (k.tag && (/^gfx_/.test((k.a && k.a.id) || ''))) { const f = o.figs && o.figs[k.a.id]; if (f) top.push(...f.map(q => ({ ...q }))); return; }
      if (k.tag && (has(k, 'alert') || k.tag === 'p')) { blocks({ kids: [k] }, o, top); return; }
      if (k.tag) walk(k);
    });
    walk(T);
    return { subs, top };
  }
  /* inline(html): a piece of the app's HTML as report text (sub / sup as $…$, tab links as in-app links), e.g. a graphic's title for its caption */
  const inline = html => line(parse(html), { X: { vals: [] }, sec: '', inReport: () => false });
  window.PSBReportTab = { parse, cards, texOf, dec, inline };
})();
